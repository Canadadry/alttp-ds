{
	assert(id < RANDO_SHOP_COUNT);
	return &shop_table[id];
}

RandoLocationId rando_location_find(const char *name)
{
	int i;

	for (i = 0; i < RANDO_LOCATION_COUNT; i++)
		if (strcmp(location_table[i].name, name) == 0)
			return (RandoLocationId)i;
	return RANDO_LOCATION_NONE;
}

RandoRegionId rando_region_find(const char *key)
{
	int i;

	for (i = 0; i < RANDO_REGION_COUNT; i++)
		if (strcmp(region_table[i].key, key) == 0)
			return (RandoRegionId)i;
	return RANDO_REGION_NONE;
}

RandoShopId rando_shop_find(const char *name)
{
	int i;

	for (i = 0; i < RANDO_SHOP_COUNT; i++)
		if (strcmp(shop_table[i].name, name) == 0)
			return (RandoShopId)i;
	return RANDO_SHOP_NONE;
}

bool rando_location_is_a(RandoLocationClass location_class, RandoLocationClass base)
{
	assert(location_class < RANDO_LOCATION_CLASS_COUNT && base < RANDO_LOCATION_CLASS_COUNT);
	for (; location_class != RANDO_LOCATION_CLASS_COUNT; location_class = parent_class[location_class])
		if (location_class == base)
			return true;
	return false;
}
