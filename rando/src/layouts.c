static const Layout *layout(RandoVariant variant)
{
	assert(variant < RANDO_VARIANT_COUNT);
	return layouts[variant];
}

int rando_layout_location_count(RandoVariant variant)
{
	return layout(variant)->nlocations;
}

RandoLocationId rando_layout_location(RandoVariant variant, int i)
{
	const Layout *l = layout(variant);

	assert(i >= 0 && i < l->nlocations);
	return (RandoLocationId)l->order[i];
}

RandoRegionId rando_layout_location_region(RandoVariant variant, RandoLocationId location)
{
	assert(location < RANDO_LOCATION_COUNT);
	return (RandoRegionId)layout(variant)->locations[location].region;
}

const RandoLayoutLocation *rando_layout_locations(RandoVariant variant)
{
	return layout(variant)->locations;
}

const uint8_t *rando_layout_order(RandoVariant variant)
{
	return layout(variant)->order;
}

int rando_layout_region_location_count(RandoVariant variant, RandoRegionId region)
{
	assert(region < RANDO_REGION_COUNT);
	return layout(variant)->regions[region].count;
}

RandoLocationId rando_layout_region_location(RandoVariant variant, RandoRegionId region, int i)
{
	const Layout *l = layout(variant);

	assert(region < RANDO_REGION_COUNT && i >= 0 && i < l->regions[region].count);
	return (RandoLocationId)l->order[l->regions[region].first + i];
}

RandoLocationId rando_layout_region_prize(RandoVariant variant, RandoRegionId region)
{
	assert(region < RANDO_REGION_COUNT);
	return (RandoLocationId)layout(variant)->regions[region].prize;
}
